export function matchLocale(preferences) {
  for (const preference of preferences) {
    try {
      const {language,script,region}=new Intl.Locale(preference);
      if(language==='en')return 'en';
      if(language==='zh'){
        if(script==='Hant')return 'zh-Hant';
        if(script==='Hans')return 'zh-Hans';
        return ['TW','HK','MO'].includes(region) ? 'zh-Hant' : 'zh-Hans';
      }
    }catch{
      // Skip a malformed locale and try the next browser preference.
    }
  }
  return 'en';
}
